# Summons that, like some bosses, wait at 0 HP for an execution: the run forces their Kill as it does the boss's
# and logs their state. LionDancer_P2 creates its own poles (GAA_FindOrCreatePole); what blocked it was the last
# lion head (tag HouHouHou.LastOne) that could not be executed, so the boss could not die (Nexus, 0.1.1).
SUMMONS = {
    'BP_Monster_LionDancer_P2': ['BP_Monster_DaTouWaWa_HouHouHou_C'],
}
# Bosses still being tried: offered in development builds only (config.debug); "open" once tested in game.
# BP_Monster_YuBi passed on 2026-11-13 (CA_02 storm arena opened in the challenge arena, pz_dock).
# BP_Monster_GuiChai_Red_P2 needs no helper (its CA_02 spawns its own safe zone); it was "origin" only because it
# was grouped with phase 1.
# BP_Monster_MoTian, BP_Monster_MoTian_LongZhu_01: no level lookup found (Skill_08 spawns its own pillars); they
# were closed only because their spawner sits in a level-only space.
testing = ['BP_Monster_MengHua', 'BP_Monster_FemaleVessel_YuZan', 'BP_Monster_DuYanBoss', 'BP_Monster_YanQianSui',
           'BP_Monster_CanQu_BiHai', 'BP_Monster_GuiChai_Red', 'BP_Monster_GuiChai_Red_P2', 'BP_Monster_ChiLian_P2',
           'BP_Monster_MoTian', 'BP_Monster_MoTian_LongZhu_01', 'BP_Monster_LionDancer_P2']


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


lines = ['-- Generated by src/tools/gen_roster.py from pbzero bosses.json.',
         '-- state: "open" | "testing" (development builds only) | "origin" (needs its own level: 单挑 only, at its original arena) | "anchored" (needs its level, arena unknown: closed) | "story" (prologue/tutorial variant)',
         '-- helpers: helper points placed before the boss spawns: class, offset from the arena centre along the arena facing (cm).',
         '-- summons: classes of the boss\'s summons that wait at 0 HP for an execution (their Kill is forced like the boss\'s).',
         'return {']
# Level-dependent bosses with a known original arena (src/mod/BossRush/Scripts/origins.lua, src/tools/origin_arenas.py):
# offered in 单挑 only, always fought at their original arena.
import re as _re
origin_ids = set(_re.findall(r'"(BP_Monster_\w+)"', open(SCRIPTS / 'origins.lua', encoding='utf-8').read()))

counts = {}
for x in b:
    st = 'open'
    if any(k.lower() in x['id'].lower() for k in story) or 'Prologue' in x.get('name_en', ''):
        st = 'story'
    elif x['id'] in testing:
        st = 'testing'
    elif x['id'] in origin_ids:
        st = 'origin'
    elif any(k.lower() in x['id'].lower() for k in anchored):
        st = 'anchored'
    counts[st] = counts.get(st, 0) + 1
    helpers = ''
    if x['id'] in HELPERS:
        helpers = ', helpers = { %s }' % ', '.join('{ class = %s, fwd = %d, right = %d }' % (q(c), f, r)
                                                   for c, f, r in HELPERS[x['id']])
    if x['id'] in SUMMONS:
        helpers += ', summons = { %s }' % ', '.join(q(c) for c in SUMMONS[x['id']])
    lines.append('    { id = %s, zh = %s, en = %s, class = %s, state = %s%s },'
                 % (q(x['id']), q(x['name']), q(x['name_en']), q(x['class_path']), q(st), helpers))
lines.append('}')
open(SCRIPTS / 'roster.lua', 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(counts)
