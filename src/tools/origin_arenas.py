"""Original arenas of the level-dependent bosses (DESIGN §5.4).

Positions are the content-bounds centres of the World Partition cells that hold each boss's helper point
(probe F3, src/data/anchor_cells_round1.tsv); the helper actor itself gives the exact spot at run time. For each arena the
nearest surface bell (by XY) is the teleport landing: World Partition streams by XY, so standing there loads the
helper's cell even when it lies in an interior space far above. Prints the Lua table for arenas.lua.
"""
import csv
import math
from pathlib import Path

SRC = Path(__file__).resolve().parents[1]     # src/

# Autotest 2026-11-13: Danghui still flew to (0,0,0) at its centre point: stays closed ("anchored").
# Lion Dance Grandmaster phase 2 fell ~42 m when the player was put on a pole base: the poles are special-move
# volumes. It now uses stay=True: the player stays at the nearby bell (尊主封印地, 14 m from the poles) and the
# boss is spawned facing the poles. Closed again on 2026-11-13: the last lion head (HouHouHou.LastOne) could be
# executed in one test but not in the next, and while it lives the boss cannot be killed, so the run gets stuck.
# Its entry (with stay=True) was:
#   (["BP_Monster_LionDancer_P2"], "/Game/Maps/B09/PBZ_Houjie_WP",
#    "/Game/RenewalContent/Actors/SpecialMove/Volume/BP_LionDancing_Pole_Base.BP_LionDancing_Pole_Base_C",
#    -271959, 48000, True),
ARENAS = [
    # boss ids, map, helper class path, cell centre x y
    (["BP_Monster_FemaleVessel_YuZan"], "/Game/Maps/B04_05/PBZ_Zhengdaodaying_WP",
     "/PBZCombatAsset/ActorData/Mobs/068_YuZan/BP_YuZan_CA_Snap_Center.BP_YuZan_CA_Snap_Center_C", -61841, 86183),
    (["BP_Monster_CanQu_BiHai"], "/Game/Maps/B04_05/PBZ_Zhengdaodaying_WP",
     "/PBZCombatAsset/ActorData/Mobs/CanQu_BiHai/Ability/Passive/BP_Monster_CanQu_BiHai_ToCenter.BP_Monster_CanQu_BiHai_ToCenter_C", -60784, 105600),
    (["BP_Monster_DuYanBoss"], "/Game/Maps/B08_09_10/PBZ_Pangzhen_WP",
     "/PBZCombatAsset/ActorData/Mobs/059_DuYan/BP_DuYan_CA_Snap_Center.BP_DuYan_CA_Snap_Center_C", -10405, -2070),
    (["BP_Monster_GuiChai_Red", "BP_Monster_GuiChai_Red_P2"], "/Game/Maps/B08_09_10/PBZ_Pangzhen_WP",
     "/PBZCombatAsset/ActorData/Mobs/069_GuiChai_Red/Setup/BP_Monster_GuiChai_Red_SnapPoint_01.BP_Monster_GuiChai_Red_SnapPoint_01_C", -169600, 131688),
    (["BP_Monster_YanQianSui"], "/Game/Maps/B08_09_10/PBZ_Pangzhen_WP",
     "/PBZCombatAsset/ActorData/Mobs/073_YanQianSui/BP_YanQianSui_SnapPoint.BP_YanQianSui_SnapPoint_C", -123862, 73371),
    (["BP_Monster_ChiLian_P2"], "/Game/Maps/B03/PBZ_Fujizhilin_WP",
     "/PBZCombatAsset/ActorData/Mobs/065_ChiLian_P2/BP_ChiLian_P2_Center.BP_ChiLian_P2_Center_C", 17403, 151532),
    (["BP_Monster_ZuoShang_Ending"], "/Game/Maps/B08_09_12_13/PBZ_Duanhun_WP",
     "/PBZCombatAsset/ActorData/Mobs/054_ZuoShang/BP_ZuoShang_CA_03_SnapPoint.BP_ZuoShang_CA_03_SnapPoint_C", -193019, -119069),
]

bells = [r for r in csv.DictReader(open(SRC / "data" / "bells.tsv", encoding="utf-8"), delimiter="\t")]
ground = [b for b in bells if abs(float(b["teleport_z"])) < 100000]

out = ["-- Generated by src/tools/origin_arenas.py", "return {"]
for entry in ARENAS:
    ids, mp, helper, x, y = entry[:5]
    stay = len(entry) > 5 and entry[5]
    best = min(ground, key=lambda b: math.hypot(float(b["teleport_x"]) - x, float(b["teleport_y"]) - y))
    d = math.hypot(float(best["teleport_x"]) - x, float(best["teleport_y"]) - y) / 100
    out.append('    { bosses = { %s }, map = "%s", helper = "%s",' % (", ".join('"%s"' % i for i in ids), mp, helper))
    out.append('      hx = %d, hy = %d, bell = "%s", bx = %s, by = %s, bz = %s, near_m = %d%s },'
               % (x, y, best["id"], best["teleport_x"], best["teleport_y"], best["teleport_z"], d,
                  ", stay = true" if stay else ""))
out.append("}")
open(SRC / "mod" / "BossRush" / "Scripts" / "origins.lua", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("\n".join(out))
