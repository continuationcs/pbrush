import json
b = json.load(open(r'F:\C\pbzero\src\pbzero\data\bosses.json', encoding='utf-8'))['bosses']
# Bosses whose skills need level-placed points (DESIGN 5.2) or confirmed vanishing: closed for now.
anchored = ['ZuoShang', 'LengTu', 'YuZan', 'GuiChai_Red', 'QiShu', 'DuYan', 'ChiLian_P2', 'MoYuan', 'MoTian',
            'YanQianSui', 'CanQu', 'DangHui']
story = ['Tutorial', 'HorseCart', 'Prologue']


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


lines = ['-- Generated by tools/gen_roster.py from pbzero bosses.json.',
         '-- state: "open" | "anchored" (skills need level-placed points, closed for now) | "story" (prologue/tutorial variant)',
         'return {']
counts = {}
for x in b:
    st = 'open'
    if any(k.lower() in x['id'].lower() for k in story) or 'Prologue' in x.get('name_en', ''):
        st = 'story'
    elif any(k.lower() in x['id'].lower() for k in anchored):
        st = 'anchored'
    counts[st] = counts.get(st, 0) + 1
    lines.append('    { id = %s, zh = %s, en = %s, class = %s, state = %s },'
                 % (q(x['id']), q(x['name']), q(x['name_en']), q(x['class_path']), q(st)))
lines.append('}')
open(r'G:\C\pbrush\mod\BossRush\Scripts\roster.lua', 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(counts)
